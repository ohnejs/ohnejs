import { rejects, strictEqual } from 'node:assert';
import { execFileSync } from 'node:child_process';
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  realpathSync,
  rmSync,
  symlinkSync,
  writeFileSync,
} from 'node:fs';
import { stripTypeScriptTypes } from 'node:module';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { after, afterEach, before, describe, it } from 'node:test';

import { generateAPITypes } from '../../../src/ohne/codegen/generate-api-types.ts';
import { generateProject, loadLayers, useLayers } from '../../../src/ohne/index.ts';

const ohne = new URL('../../../src/ohne/index.ts', import.meta.url).href;
const TSC = join(import.meta.dirname, '..', '..', '..', 'node_modules', 'typescript', 'bin', 'tsc');

describe('generateAPITypes', () => {
  let root: string;

  function write(file: string, content: string): void {
    mkdirSync(join(file, '..'), { recursive: true });
    writeFileSync(file, content);
  }

  function writeApp(name: string, config: string): string {
    const app = join(root, name, 'backend');
    write(
      join(app, 'package.json'),
      JSON.stringify({ name, type: 'module', dependencies: { kit: '*' } }),
    );
    write(join(app, 'ohne.config.ts'), `export default ${config};\n`);
    const kit = join(root, name, 'kit');
    write(join(kit, 'package.json'), JSON.stringify({ name: 'kit', type: 'module' }));
    write(join(kit, 'ohne.config.ts'), '');
    mkdirSync(join(app, 'node_modules'), { recursive: true });
    symlinkSync(kit, join(app, 'node_modules', 'kit'), 'dir');
    write(join(kit, 'api', 'me.get.ts'), 'export default () => null;\n');
    write(join(kit, 'api', 'ping.get.ts'), 'export default () => null;\n');
    write(
      join(kit, 'ohne.contract.ts'),
      "export interface User {\n  id: string;\n}\n\nexport interface Routes {\n  'GET /me': { response: User };\n  'GET /ping': { response: 'pong' };\n}\n",
    );
    write(join(app, 'api', 'sites', '[code].get.ts'), 'export default () => null;\n');
    write(join(app, 'api', 'hidden.get.ts'), 'export default () => null;\n');
    write(
      join(app, 'shared', 'sites.ts'),
      '/**\n * One site.\n */\nexport interface Site {\n  code: string;\n}\n',
    );
    write(
      join(app, 'ohne.contract.ts'),
      "import type { Site } from './shared/sites.ts';\n\n" +
        "export type { Site } from './shared/sites.ts';\n\n" +
        "export interface Routes {\n  'GET /sites/[code]': { query: { full?: boolean }; response: Site };\n" +
        "  'GET /ping': { response: 'PONG' };\n}\n",
    );
    return app;
  }

  before(() => {
    root = realpathSync(mkdtempSync(join(tmpdir(), 'ohne-gen-api-types-')));
  });

  after(() => {
    rmSync(root, { recursive: true, force: true });
  });

  afterEach(() => {
    useLayers().clear();
  });

  it('types every live route by the closest contract, in a file that imports nothing', async () => {
    const app = writeApp(
      'types',
      "{ layers: ['kit'], api: { types: '../web/ohne.ts' }, disable: { routes: ['GET /hidden'] } }",
    );
    await loadLayers(app);

    const text = await generateAPITypes();

    strictEqual(text.startsWith('// Generated by ohne from `../backend`. Do not edit.\n'), true);
    strictEqual(
      text.includes(
        "export type RouteID =\n  | 'GET /me'\n  | 'GET /ping'\n  | 'GET /sites/[code]';\n",
      ),
      true,
    );
    strictEqual(
      text.includes('type Contracts = Omit<L0.Routes, keyof Contract.Routes> & Contract.Routes;'),
      true,
    );
    strictEqual(text.includes('declare namespace L0 {\n  export interface User {'), true);
    strictEqual(
      text.includes(
        'export declare namespace Contract {\n  import Site = M2.Site;\n\n  export import Site = M2.Site;',
      ),
      true,
    );
    strictEqual(text.includes('declare namespace M2 {\n  /**\n   * One site.\n   */'), true);
    strictEqual(/^import /m.test(text), false);
  });

  it('compiles under strict erasable syntax and strips to nothing under Node', async () => {
    const app = writeApp('compile', "{ layers: ['kit'], api: { types: '../web/ohne.ts' } }");
    await loadLayers(app);
    await generateProject(app, { paths: true });
    const web = join(root, 'compile', 'web');
    write(join(web, 'package.json'), JSON.stringify({ type: 'module' }));
    write(
      join(web, 'use.ts'),
      "import type { Contract, RouteID, Routes } from './ohne.ts';\n\n" +
        "export const site: Routes['GET /sites/[code]']['response'] = { code: 'a' };\n" +
        'export const named: Contract.Site = site;\n' +
        "export const ping: Routes['GET /ping']['response'] = 'PONG';\n" +
        "export const me: Routes['GET /me']['response'] = { id: '1' };\n" +
        "export const id: RouteID = 'GET /sites/[code]';\n" +
        "export const query: Routes['GET /sites/[code]']['query'] = { full: true };\n" +
        'type Equal<A, B> = (<T>() => T extends A ? 1 : 2) extends <T>() => T extends B ? 1 : 2 ? true : false;\n' +
        "export const uncontracted: Equal<Routes['GET /hidden'], {}> = true;\n",
    );
    write(
      join(web, 'tsconfig.json'),
      JSON.stringify({
        compilerOptions: {
          strict: true,
          erasableSyntaxOnly: true,
          verbatimModuleSyntax: true,
          isolatedModules: true,
          module: 'nodenext',
          target: 'esnext',
          noEmit: true,
          allowImportingTsExtensions: true,
          types: [],
        },
        files: ['ohne.ts', 'use.ts'],
      }),
    );

    execFileSync(process.execPath, [TSC, '-p', web], { encoding: 'utf8' });
    const stripped = stripTypeScriptTypes(readFileSync(join(web, 'ohne.ts'), 'utf8'));
    strictEqual(stripped.replace(/\/\*[\s\S]*?\*\/|\/\/.*/g, '').trim(), '');
  });

  it('is written by `ohne prepare` and `ohne dev`, never by a booting process', async () => {
    const app = writeApp('paths', "{ layers: ['kit'], api: { types: '../web/ohne.ts' } }");
    const out = join(root, 'paths', 'web', 'ohne.ts');
    await loadLayers(app);

    await generateProject(app);
    strictEqual(existsSync(out), false);

    const written = await generateProject(app, { paths: true });
    strictEqual(written.includes(out), true);
  });

  it('refuses a path a layer entry claims too', async () => {
    const app = writeApp('claimed', "{ layers: ['kit'], api: { types: 'out.ts' } }");
    write(
      join(app, 'ohne.layer.ts'),
      `import { defineLayer } from '${ohne}';\n\n` +
        "export default defineLayer({ codegen: [{ path: () => 'out.ts', code: () => '' }] });\n",
    );
    await loadLayers(app);

    await rejects(generateProject(app, { paths: true }), /Codegen file `out.ts` is claimed twice/);
  });

  it('merges no contract when no layer has one', async () => {
    const app = join(root, 'bare');
    write(join(app, 'package.json'), JSON.stringify({ name: 'bare', type: 'module' }));
    write(join(app, 'ohne.config.ts'), "export default { api: { types: 'ohne.ts' } };\n");
    await loadLayers(app);

    const text = await generateAPITypes();

    strictEqual(text.includes('export type RouteID = never;'), true);
    strictEqual(text.includes('type Contracts = {};'), true);
    strictEqual(text.includes('namespace'), false);
  });
});
