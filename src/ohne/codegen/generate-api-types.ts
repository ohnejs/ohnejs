import type { PathCodegen } from '../layers/define-layer.ts';

import {
  type CodeBuilder,
  createCodeBuilder,
  jsdocBlock,
  literalString,
} from '../../utils/codegen/index.ts';
import { dirname, isUndefined, last, relativePath, resolvePath } from '../../utils/index.ts';
import { collectContracts } from '../contracts/collect-contracts.ts';
import { readContractModules } from '../contracts/read-contract-modules.ts';
import { stackedLayers } from '../layers/stacked-layers.ts';
import { useConfig } from '../layers/use-config.ts';
import { collectRoutes } from '../routes/collect-routes.ts';
import { routeID, type RouteMeta } from '../routes/route.ts';

/**
 * The framework's own path codegen entry: the `api.types` file, written like any layer's path entry.
 */
export const apiTypesCodegen: PathCodegen = {
  path: () => useConfig().api.types,
  code: () => generateAPITypes(),
};

/**
 * Generates the text of the `api.types` file: your routes' types for a frontend in another package.
 *
 * `RouteID` lists every route left after `disable.routes`.
 * `Routes` maps each id to its contract, or to `{}` when no layer's `ohne.contract.ts` declares one.
 * A closer layer's entry wins per id, as its route does.
 * Each contract module is copied into its own `declare namespace`, so the file imports nothing.
 * The names the app's own contract exports read as `Contract.Name`.
 *
 * A contract module that holds runtime code, or that the copy cannot carry, throws a block at its position.
 * Layers come from the registered stack, so `loadLayers` must have run first.
 */
export async function generateAPITypes(): Promise<string> {
  const layers = stackedLayers();
  const app = last(layers)?.dir ?? process.cwd();
  const out = useConfig().api.types;
  const entries = await collectContracts(layers);
  const modules = await readContractModules(
    entries.map((entry) => entry.file),
    { app: entries.find((entry) => dirname(entry.file) === app)?.file },
  );
  const routes = await collectRoutes(layers, { disable: useConfig().disable.routes });
  const namespaces = new Map(modules.map((module) => [module.file, module.name]));
  const routeMaps = entries.map((entry) => `${namespaces.get(entry.file)}.Routes`);
  const from = isUndefined(out) ? '.' : relativePath(dirname(resolvePath(out, app)), app) || '.';

  const code = createCodeBuilder();
  code.line(`// Generated by ohne from \`${from}\`. Do not edit.`);
  code.line();
  code.line(jsdocBlock('Every route id your API serves.'));
  emitRouteIDs(code, 'export type RouteID', routes);
  code.line();
  code.line(jsdocBlock("Each route's contract by id.\nA route without one answers `unknown`."));
  code.line(
    'export type Routes = { [K in RouteID]: K extends keyof Contracts ? Contracts[K] : {} };',
  );
  code.line();
  code.line(`type Contracts = ${closerWins(routeMaps)};`);
  for (const module of modules) {
    code.line();
    if (module.name === 'Contract') {
      code.line(jsdocBlock("The names your app's `ohne.contract.ts` exports."));
      code.line('export declare namespace Contract {');
    } else code.line(`declare namespace ${module.name} {`);
    if (module.text !== '') code.line(module.text);
    code.line('}');
  }
  return code.toString();
}

/**
 * Merges route maps given furthest first into one type, a closer map's entry winning per id.
 */
export function closerWins(maps: readonly string[]): string {
  if (maps.length === 0) return '{}';
  return maps.reduce((merged, map) => `Omit<${merged}, keyof ${map}> & ${map}`);
}

/**
 * Emits `head` as the union of every route id in `routes`, one id per line, or `never` for none.
 */
export function emitRouteIDs(code: CodeBuilder, head: string, routes: readonly RouteMeta[]): void {
  if (routes.length === 0) {
    code.line(`${head} = never;`);
    return;
  }
  code.line(`${head} =`);
  code.indent(() => {
    routes.forEach((route, i) => {
      const end = i === routes.length - 1 ? ';' : '';
      code.line(`| ${literalString(routeID(route.method, route.pattern))}${end}`);
    });
  });
}
